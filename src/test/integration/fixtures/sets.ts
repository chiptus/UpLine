import type { Database } from "@/integrations/supabase/types";
import { registerCleanup, testSupabase } from "../harness";
import { SEEDED_USER_ID } from "./constants";
import { createScratchFestivalEdition } from "./scratchPool";

type SetInsert = Database["public"]["Tables"]["sets"]["Insert"];

/**
 * Creates a uniquely-named set and self-registers its cleanup.
 * @param overrides.festival_edition_id - defaults to a fresh scratch edition when omitted.
 */
export async function createSet(
  overrides: Partial<SetInsert> = {},
): Promise<string> {
  const suffix = crypto.randomUUID();
  const festival_edition_id =
    overrides.festival_edition_id ?? (await createScratchFestivalEdition());

  const { data, error } = await testSupabase
    .from("sets")
    .insert({
      name: `Scratch Set ${suffix}`,
      slug: "", // auto-generated by the sets_dedupe_slug DB trigger
      created_by: SEEDED_USER_ID,
      ...overrides,
      festival_edition_id,
    })
    .select("id")
    .single();
  if (error) throw error;

  registerCleanup(async () => {
    const { error: deleteError } = await testSupabase
      .from("sets")
      .delete()
      .eq("id", data.id);
    if (deleteError) throw deleteError;
  });

  return data.id;
}
